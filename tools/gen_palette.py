#!/usr/bin/env python3
"""Generate the Material 3 brand colour scheme (used when dynamic colour is unavailable or off).

Needs:  pip install materialyoucolor
Usage:  python3 tools/gen_palette.py [#RRGGBB]     (default seed below)
Writes: app/src/main/kotlin/com/gng/app/ui/theme/BrandColors.kt
"""
import pathlib
import sys

from materialyoucolor.dynamiccolor.material_dynamic_colors import MaterialDynamicColors
from materialyoucolor.hct import Hct
from materialyoucolor.scheme.scheme_tonal_spot import SchemeTonalSpot
from materialyoucolor.scheme.scheme_vibrant import SchemeVibrant

SEED = "#E8506E"  # refined pink-coral
TERTIARY_SEED = "#17A398"  # teal: the accent for "free", "going" and "online" states
SPEC = "2021"  # classic Material 3 role mapping
ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "app/src/main/kotlin/com/gng/app/ui/theme/BrandColors.kt"

# Compose ColorScheme parameters (materialyoucolor uses the same camelCase role names).
ROLES = [
    "primary", "onPrimary", "primaryContainer", "onPrimaryContainer", "inversePrimary",
    "secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer",
    "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer",
    "background", "onBackground", "surface", "onSurface", "surfaceVariant", "onSurfaceVariant",
    "surfaceTint", "inverseSurface", "inverseOnSurface",
    "error", "onError", "errorContainer", "onErrorContainer",
    "outline", "outlineVariant", "scrim",
    "surfaceBright", "surfaceDim", "surfaceContainer", "surfaceContainerHigh",
    "surfaceContainerHighest", "surfaceContainerLow", "surfaceContainerLowest",
]


def argb(seed_hct, dark):
    scheme = SchemeVibrant(seed_hct, dark, 0.0, spec_version=SPEC)
    colors = MaterialDynamicColors(SPEC)
    out = {}
    for role in ROLES:
        out[role] = getattr(colors, role).get_argb(scheme) & 0xFFFFFFFF
    return out


def with_accents(values, seed_hct, tertiary_hct, dark):
    """Pink primary (Vibrant), a calm rosy secondary (Tonal Spot of the same seed) and a teal tertiary."""
    colors = MaterialDynamicColors(SPEC)
    rosy = SchemeTonalSpot(seed_hct, dark, 0.0, spec_version=SPEC)
    teal = SchemeTonalSpot(tertiary_hct, dark, 0.0, spec_version=SPEC)
    for role in ("secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer"):
        values[role] = getattr(colors, role).get_argb(rosy) & 0xFFFFFFFF
    # Teal's *primary* roles become our tertiary roles.
    for role, source in (("tertiary", "primary"), ("onTertiary", "onPrimary"),
                         ("tertiaryContainer", "primaryContainer"), ("onTertiaryContainer", "onPrimaryContainer")):
        values[role] = getattr(colors, source).get_argb(teal) & 0xFFFFFFFF
    return values


def kotlin(name, values):
    lines = [f"internal val {name} = {'darkColorScheme' if 'Dark' in name else 'lightColorScheme'}("]
    for role in ROLES:
        lines.append(f"    {role} = Color(0x{values[role]:08X}),")
    lines.append(")")
    return "\n".join(lines)


def main():
    seed = (sys.argv[1] if len(sys.argv) > 1 else SEED).lstrip("#")
    hct = Hct.from_int(0xFF000000 | int(seed, 16))
    tertiary = Hct.from_int(0xFF000000 | int(TERTIARY_SEED.lstrip("#"), 16))
    light = with_accents(argb(hct, False), hct, tertiary, False)
    dark = with_accents(argb(hct, True), hct, tertiary, True)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "package com.gng.app.ui.theme\n\n"
        "import androidx.compose.material3.darkColorScheme\n"
        "import androidx.compose.material3.lightColorScheme\n"
        "import androidx.compose.ui.graphics.Color\n\n"
        f"// Generated by tools/gen_palette.py from seed #{seed.upper()} (Material 3 Vibrant, 2021 spec, teal tertiary).\n"
        "// Used when dynamic colour is unavailable (Android 11 and older) or switched off.\n\n"
        + kotlin("BrandLightColors", light) + "\n\n" + kotlin("BrandDarkColors", dark) + "\n"
    )
    print(f"seed #{seed.upper()}: primary light {light['primary']:08X} / dark {dark['primary']:08X}; "
          f"container {light['primaryContainer']:08X}; secondary {light['secondary']:08X}; tertiary {light['tertiary']:08X}")


main()
