#!/usr/bin/env python3
"""Fetch Material Symbols (Rounded) and convert them to Android vector drawables.

Reads tools/icons.txt, writes app/src/main/res/drawable/ic_<name>.xml (and ic_<name>_fill.xml
for names marked with "+"), plus app/src/main/kotlin/com/gng/app/ui/icons/GngIcons.kt.

Material Symbols are licensed under Apache 2.0 (https://github.com/google/material-design-icons).
"""
import pathlib
import re
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res/drawable"
KT = ROOT / "app/src/main/kotlin/com/gng/app/ui/icons/GngIcons.kt"
BASE = "https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsrounded/{name}/{style}/24px.svg"
MIRRORED = {"arrow_back", "arrow_forward", "chevron_right", "send", "logout", "reply", "open_in_new", "help"}


def fetch(name: str, style: str) -> str:
    url = BASE.format(name=name, style=style)
    try:
        with urllib.request.urlopen(url, timeout=30) as r:
            return r.read().decode()
    except Exception as e:  # noqa: BLE001
        raise SystemExit(f"Could not fetch {name} ({style}): {e}\n  {url}")


def to_vector(svg: str, mirrored: bool) -> str:
    paths = re.findall(r'<path[^>]*\sd="([^"]+)"', svg)
    if not paths:
        raise ValueError("no path in svg")
    body = "\n".join(
        f'        <path\n            android:fillColor="#FF000000"\n            android:pathData="{d}" />' for d in paths
    )
    mirror = '\n    android:autoMirrored="true"' if mirrored else ""
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Material Symbols Rounded (Apache 2.0). Generated by tools/fetch_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"{mirror}
    android:viewportWidth="960"
    android:viewportHeight="960">
    <group android:translateY="960">
{body}
    </group>
</vector>
"""


def camel(name: str) -> str:
    return "".join(p.capitalize() for p in name.split("_"))


def main() -> None:
    RES.mkdir(parents=True, exist_ok=True)
    KT.parent.mkdir(parents=True, exist_ok=True)
    entries = []
    for line in (ROOT / "tools/icons.txt").read_text().splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        filled = line.endswith("+")
        entries.append((line.rstrip("+"), filled))

    for name, filled in entries:
        (RES / f"ic_{name}.xml").write_text(to_vector(fetch(name, "default"), name in MIRRORED))
        if filled:
            (RES / f"ic_{name}_fill.xml").write_text(to_vector(fetch(name, "fill1"), name in MIRRORED))
        print("ok", name, "(+fill)" if filled else "")

    lines = [
        "package com.gng.app.ui.icons",
        "",
        "import androidx.annotation.DrawableRes",
        "import com.gng.app.R",
        "",
        "// Generated by tools/fetch_icons.py from tools/icons.txt. Do not edit by hand.",
        "// Material Symbols Rounded, Apache 2.0.",
        "object GngIcons {",
    ]
    for name, filled in entries:
        lines.append(f"    @DrawableRes val {camel(name)} = R.drawable.ic_{name}")
        if filled:
            lines.append(f"    @DrawableRes val {camel(name)}Fill = R.drawable.ic_{name}_fill")
    lines += ["}", ""]
    KT.write_text("\n".join(lines))
    print(f"wrote {len(entries)} icons -> {KT.relative_to(ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
